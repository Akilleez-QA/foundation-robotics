import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from foundation_robotics.sources import CALIBRATION, DEFAULTS
from foundation_robotics_bridge.schemas import tool_definitions
from foundation_robotics_bridge.server import LIMITS, PROTOCOL

CATALOG = ROOT / "docs/guides/reference/tool-catalog.md"
DEFAULTS_DOC = ROOT / "docs/data/defaults.md"
CALIBRATION_DOC = ROOT / "docs/data/calibration-cases.md"
HEADER = "Generated by `python -B tools/gen_docs.py`. Do not edit by hand; `tests/test_docs.py` fails when this file is stale."


def kind(schema):
    if "const" in schema:
        return f"const {json.dumps(schema['const'])}"
    if "enum" in schema:
        return "one of " + ", ".join(f"`{v}`" for v in schema["enum"])
    if "anyOf" in schema or "oneOf" in schema:
        options = schema.get("anyOf", schema.get("oneOf"))
        return " or ".join(kind(o) for o in options)
    t = schema.get("type")
    if type(t) is list:
        return " or ".join(t)
    if t == "integer":
        return f"integer {schema['minimum']}..{schema['maximum']}"
    if t == "string":
        if "pattern" in schema:
            return f"string matching `{schema['pattern']}`"
        return f"string up to {schema['maxLength']} chars"
    if t == "array":
        return f"array[{schema['minItems']}..{schema['maxItems']}] of {kind(schema['items'])}"
    if t == "object" and "properties" in schema:
        return "object"
    if t == "object":
        return f"map[{schema.get('minProperties', 0)}..{schema['maxProperties']}] of {kind(schema['additionalProperties'])}"
    if t == "null":
        return "null"
    if t == "boolean":
        return "boolean"
    return json.dumps(schema, sort_keys=True)


def walk(schema, prefix, rows):
    for name, sub in schema.get("properties", {}).items():
        path = f"{prefix}{name}"
        rows.append((path, kind(sub), "yes" if name in schema.get("required", []) else "no"))
        inner = sub
        while inner.get("type") == "array":
            inner = inner["items"]
            path += "[]"
        if inner.get("type") == "object" and "properties" in inner:
            walk(inner, path + ".", rows)


def table(rows):
    lines = ["| Field | Type and range | Required in its object |", "|---|---|---|"]
    bar = "\\|"
    lines += [f"| `{p}` | {k.replace('|', bar)} | {r} |" for p, k, r in rows]
    return lines


def catalog():
    tools = tool_definitions()
    raw = json.dumps(tools, ensure_ascii=True, allow_nan=False, sort_keys=True, separators=(",", ":")).encode("ascii")
    out = ["# Tool catalog", "", HEADER, "",
           f"Protocol `{PROTOCOL}`. Canonical tool inventory SHA-256 `{hashlib.sha256(raw).hexdigest()}` "
           "(the same value `tools/build_manifest.py` prints as `inventory_sha256`).", "",
           "## Bridge limits", "", "| Limit | Value |", "|---|---|"]
    out += [f"| `{k}` | {v} |" for k, v in LIMITS.items()]
    out += ["", "## Common result envelope", "",
            "Every `tools/call` result has `structuredContent` with `tool`, `assessment`, `formal_proof` (always "
            "false), `runtime_goal_acceptance` (always false) and `receipt`. The receipt fields are:", ""]
    rows = []
    walk(tools[0]["outputSchema"]["properties"]["receipt"], "receipt.", rows)
    out += table([r for r in rows if not r[0].startswith("receipt.result")])
    for tool in tools:
        out += ["", f"## `{tool['name']}`", "", tool["description"], "",
                "Assessments: " + ", ".join(f"`{a}`" for a in tool["outputSchema"]["properties"]["assessment"]["enum"])
                + ".", "", "### Input", ""]
        schema = tool["inputSchema"]
        if "oneOf" in schema:
            for variant in schema["oneOf"]:
                rows = []
                walk(variant, "", rows)
                out += [f"Variant `kind = {variant['properties']['kind']['const']}`:", ""] + table(rows) + [""]
            out.pop()
        else:
            rows = []
            walk(schema, "", rows)
            out += table(rows)
        result = tool["outputSchema"]["properties"]["receipt"]["properties"]["result"]["oneOf"][1]
        rows = []
        walk(result, "result.", rows)
        out += ["", "### Result", ""] + table(rows)
    return "\n".join(out) + "\n"


def defaults():
    out = ["# Default values", "", HEADER, "", "Source: `foundation_robotics/data/defaults.json` (schema "
           f"`{DEFAULTS['schema']}`). Status `RECORDED` means a cited constant or measured ratio; `CHECK` means a "
           "threshold not yet approved by a qualified person. Source keys resolve in `foundation_robotics/sources.py`.",
           "", "| Section | Key | Value | Unit | Status | Source key | Note |", "|---|---|---|---|---|---|---|"]
    for section, values in DEFAULTS.items():
        if type(values) is not dict:
            continue
        for key, entry in values.items():
            note = entry.get("note", "").replace("|", "\\|")
            out.append(f"| {section} | `{key}` | {json.dumps(entry['value'])} | {entry['unit']} | {entry['status']} | "
                       f"`{entry['source']}` | {note} |")
    return "\n".join(out) + "\n"


def calibration():
    out = ["# Calibration cases", "", HEADER, "", "Source: `foundation_robotics/data/calibration.json` (schema "
           f"`{CALIBRATION['schema']}`). `CalibrationTests.test_every_recorded_case_reaches_its_verdict` replays "
           "every case and fails if a verdict or failing-check set changes.", "",
           "| Case | Tool | Label | Expected verdict | Failing checks |", "|---|---|---|---|---|"]
    for case in CALIBRATION["cases"]:
        fails = ", ".join(f"`{f}`" for f in case.get("fails", [])) or "none"
        out.append(f"| `{case['id']}` | `{case['tool']}` | {case['label']} | `{case['verdict']}` | {fails} |")
    return "\n".join(out) + "\n"


OUTPUTS = {CATALOG: catalog, DEFAULTS_DOC: defaults, CALIBRATION_DOC: calibration}


def main():
    stale = []
    for path, build in OUTPUTS.items():
        text = build()
        if sys.argv[1:] == ["--check"]:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        print("stale generated docs: " + ", ".join(stale) + "; run python -B tools/gen_docs.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
